export const getCaseById = (id) => {
  return INVESTIGATION_CASES.find((c) => c.id === id)
}

export const getCasesByDifficulty = (difficulty) => {
  return INVESTIGATION_CASES.filter((c) => c.difficulty === difficulty)
}

export const getCasesByCategory = (category) => {
  return INVESTIGATION_CASES.filter((c) => c.category === category)
}

export const sortCasesByPrice = (cases, order = 'asc') => {
  return [...cases].sort((a, b) => {
    return order === 'asc' ? a.price - b.price : b.price - a.price
  })
}

export const sortCasesByRating = (cases) => {
  return [...cases].sort((a, b) => b.rating - a.rating)
}

export const sortCasesByNewest = (cases) => {
  return [...cases].sort(
    (a, b) => new Date(b.publicationDate) - new Date(a.publicationDate)
  )
}
